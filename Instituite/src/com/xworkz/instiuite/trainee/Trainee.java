package com.xworkz.instiuite.trainee;

public class Trainee {
  private   String traineeName;

   private String trainingHours;

   private String domain;

   private  int trainingFee;

    public String getTraineeName() {
        return traineeName;
    }

    public void setTraineeName(String tarineeName) {
        this.traineeName = tarineeName;
    }

    public String getTrainingHours() {
        return trainingHours;
    }

    public void setTrainingHours(String trainingHours) {
        this.trainingHours = trainingHours;
    }

    public String getDomain() {
        return domain;
    }

    public void setDomain(String domain) {
        this.domain = domain;
    }

    public int getTrainingFee() {
        return trainingFee;
    }

    public void setTrainingFee(int trainingFee) {
        this.trainingFee = trainingFee;
    }
}

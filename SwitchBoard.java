class SwitchBoard {
    static String brand = "Anchor";
    static int numberOfSwitches = 6;
    static int numberOfSockets = 2;
    static boolean hasIndicatorLight = true;
    static String color = "White";
    static String material = "Polycarbonate";

    public static void main(String[] args) {
        System.out.println("SwitchBoard Brand: " + brand);
        System.out.println("Number of Switches: " + numberOfSwitches);
        System.out.println("Number of Sockets: " + numberOfSockets);
        System.out.println("Has Indicator Light: " + hasIndicatorLight);
        System.out.println("Color: " + color);
        System.out.println("Material: " + material);
    }
}
